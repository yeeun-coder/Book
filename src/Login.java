    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String email = txtEmail.getText().trim();
        String pw    = String.valueOf(txtPw.getPassword());
        
        if (email.isBlank() || pw.isBlank()) {
            javax.swing.JOptionPane.showMessageDialog(this, "email / 패스워드는 반드시 입력하셔야 합니다.");
            return;
        }
        
        if (false == isCheckcaptcha) {
            javax.swing.JOptionPane.showMessageDialog(this, "캡차 확인은 필수입니다.");
            return;
        }
        String SQL;
        SQL =  "select user_id, name, email from users where ";
        SQL += "email = '" + email + "' and ";
        SQL += "password = '" + pw + "' ";
        
        try {
            DB db = new DB();
            db.dbOpen();
            System.out.println("실행할 쿼리: " + SQL);
            db.dbRs = db.dbStmt.executeQuery(SQL);
            if(db.dbRs.next()){
                int userID = Integer.parseInt(db.dbRs.getString("user_id"));
                System.out.println(userID);
                new MainFrame(userID).setVisible(true);
                dispose();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "이메일 혹은 비밀번호가 다릅니다.");
                return;
            }
            db.dbRs.close();
            db.dbClose();
        } catch (Exception e) {
            System.out.println("SQLException : " + e.getMessage());
        }  
    }//GEN-LAST:event_btnLoginActionPerformed

