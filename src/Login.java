    private void btnCaptchaCheckActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCaptchaCheckActionPerformed
        
        // 사용자 입력 가져오기
        captchaManager.getDebugAnswer();
        if (captchaManager.checkAnswer(txtCaptchaINput.getText().trim())) {
            JOptionPane.showMessageDialog(null, "정답입니다.");
            btnCaptchaCheck.setEnabled(false);
            btnCaptchaRefresh.setEnabled(false);
            isCheckcaptcha = true;
            
        } else { // 실패 처리
            JOptionPane.showMessageDialog(null, "입력하신 내용이 올바르지 않습니다.");
            txtCaptchaINput.setText(""); 
               
            // 캡챠 새로고침
            lblCaptcha.setIcon(new ImageIcon(captchaManager.refreshCaptcha()));
        }
    }//GEN-LAST:event_btnCaptchaCheckActionPerformed

