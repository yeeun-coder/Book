    private void btnUploadImageActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUploadImageActionPerformed
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("책 표지 이미지 선택");
        
        // 파일 형식 제한
        chooser.setFileFilter(new FileNameExtensionFilter("이미지 파일 (JPG, PNG)", "jpg", "png", "jpeg"));
        chooser.setMultiSelectionEnabled(false); // 하나만 선택 가능

        int returnVal = chooser.showOpenDialog(this);

        // 사용자가 파일을 선택 시
        if (returnVal == JFileChooser.APPROVE_OPTION) {
            selectedFile = chooser.getSelectedFile();
            
            // 버튼 텍스트 -> 파일명
            btnUploadImage.setText(selectedFile.getName());
        }
    }//GEN-LAST:event_btnUploadImageActionPerformed

    private void btnOKActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOKActionPerformed
        String title = txtBookTitle.getText().trim();
        String category = txtBookCategory.getText().trim();
        String author = txtBookWriter.getText().trim();


        if (title.isEmpty() || author.isEmpty()) {
            JOptionPane.showMessageDialog(this, "책 제목과 저자는 필수 입력입니다.");
            return;
        }

        String dbImagePath = "/images/default.png"; 

        if (selectedFile != null) {
            try {
                String projectPath = System.getProperty("user.dir"); 
                String saveDir = projectPath + "/src/images"; 

                // 폴더 없으면 생성
                File dir = new File(saveDir);
                if (!dir.exists()) dir.mkdirs();

                // 파일 복사
                Path source = selectedFile.toPath();
                Path dest = Paths.get(saveDir + "/" + selectedFile.getName());
                Files.copy(source, dest, StandardCopyOption.REPLACE_EXISTING);

                // DB에 저장할 경로 문자열
                dbImagePath = "/images/" + selectedFile.getName();

            } catch (Exception e) {
                System.out.println("이미지 복사 실패: " + e.getMessage());
                JOptionPane.showMessageDialog(this, "이미지 업로드 중 오류가 발생했습니다. 기본 이미지로 저장합니다.");
            }
        }

        // DB 저장
        try {
            dbConnect.DB db = new dbConnect.DB();
            db.dbOpen();

            // 책 정보 저장
            String insertBookSQL = String.format(
                "INSERT INTO books (title, type, author, cover_image_url) VALUES ('%s', '%s', '%s', '%s')",
                title, category, author, dbImagePath
            );

            // 키 생성 옵션을 줘서 방금 들어간 book_id를 알아냄
            db.dbStmt.executeUpdate(insertBookSQL, Statement.RETURN_GENERATED_KEYS);

            db.dbRs = db.dbStmt.getGeneratedKeys();
            long newBookId = -1;
            if (db.dbRs.next()) {
                newBookId = db.dbRs.getLong(1);
            }

            if (newBookId != -1) {
                String insertMemorySQL = String.format(
                    "INSERT INTO book_memories (user_id, book_id, reading_status) VALUES (%d, %d, 0)",
                    currentUserId, newBookId
                );
                db.dbStmt.executeUpdate(insertMemorySQL);

                JOptionPane.showMessageDialog(this, "책이 등록되었습니다!");
                
                
                dispose(); 
            } else {
                JOptionPane.showMessageDialog(this, "책 등록에 실패했습니다.");
            }

            db.dbClose();

        } catch (Exception e) {
            System.out.println("DB Error: " + e.getMessage());
            JOptionPane.showMessageDialog(this, "DB 저장 중 오류 발생!");
        }
    }//GEN-LAST:event_btnOKActionPerformed

