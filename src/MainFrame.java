private void loadBookList(int currentUserId) {
    List<BookDTO> dbData = new ArrayList<>();

    try {
        dbConnect.DB db = new dbConnect.DB();
        db.dbOpen();

        String sql = "SELECT b.book_id, b.title, b.author, b.type, b.cover_image_url " +
                     "FROM book_memories bm " +
                     "JOIN books b ON bm.book_id = b.book_id " +
                     "WHERE bm.user_id = " + currentUserId + " " +
                     "ORDER BY bm.created_at DESC"; // 최신 등록순 정렬

        System.out.println("실행할 쿼리: " + sql);
        db.dbRs = db.dbStmt.executeQuery(sql);
        
        while (db.dbRs.next()) {
            int id = db.dbRs.getInt("book_id");
            String title = db.dbRs.getString("title");
            String author = db.dbRs.getString("author");
            String type = db.dbRs.getString("type");
            String imgPath = db.dbRs.getString("cover_image_url");
            if (imgPath == null || imgPath.isEmpty()) {
                imgPath = "/images/default.png";
            }
            dbData.add(new BookDTO(id, title, author, type, imgPath));
        }
        db.dbRs.close();
        db.dbClose();
        
    } catch (Exception e) {
        System.out.println("Book Load Error: " + e.getMessage());
        e.printStackTrace();
    }
    
    updateBookList(dbData);
}

