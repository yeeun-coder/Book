    public class BookDTO {
        int id;             // 책 고유 ID (삭제나 상세 조회시 필요)
        String title;       // 책 제목
        String author;      // 저자
        String type;        // 장르
        String imagePath;   // 이미지 경로

        public BookDTO(int id, String title, String author, String type, String imagePath) {
            this.id = id;
            this.title = title;
            this.author = author;
            this.type = type;
            this.imagePath = imagePath;
        }
    }
    

public void updateBookList(List<BookDTO> books) {
    
    bookListPanel.removeAll(); 
    
    GridLayout gridLayout = new GridLayout(0, 6, 20, 30);
    bookListPanel.setLayout(gridLayout);
    
    // 전체 패널 테두리 여백 추가
    bookListPanel.setBorder(new EmptyBorder(20, 20, 20, 20)); 

    for (BookDTO book : books) {
        JPanel itemPanel = createBookItem(book); 
        bookListPanel.add(itemPanel);
    }
    
    // 빈 공간 채우기
    int totalCells = books.size();
    int remainder = totalCells % 6;
    if (remainder != 0) {
        for (int i = 0; i < (6 - remainder); i++) {
            JPanel empty = new JPanel();
            empty.setBackground(Color.WHITE); 
            bookListPanel.add(empty);
        }
    }

    // 화면 갱신
    bookListPanel.revalidate();
    bookListPanel.repaint();
}


private JPanel createBookItem(BookDTO book) {
    JPanel cardPanel = new JPanel();
    cardPanel.setBackground(Color.WHITE);
    
    // 상단(이미지), 하단(텍스트) 분리
    cardPanel.setLayout(new BorderLayout()); 
    cardPanel.setPreferredSize(new Dimension(160, 240)); 
    

    JLabel imgLabel = new JLabel();
    imgLabel.setHorizontalAlignment(JLabel.CENTER);
    imgLabel.setBackground(Color.WHITE);
    imgLabel.setOpaque(true);
    
    try {
        ImageIcon icon;

        if (book.imagePath.startsWith("/images/")) {
            // 기본 이미지
            icon = new ImageIcon(getClass().getResource(book.imagePath));
        } else {
            // 업로드 이미지 (절대경로)
            icon = new ImageIcon(book.imagePath);
        }

        Image img = icon.getImage();
        Image updateImg = img.getScaledInstance(120, 170, Image.SCALE_SMOOTH);
        imgLabel.setIcon(new ImageIcon(updateImg));

    } catch (Exception e) {
        imgLabel.setText("No Image");
        imgLabel.setPreferredSize(new Dimension(120, 170));
    }

    // 이미지 라벨에 border 생성
    Border blackline = BorderFactory.createLineBorder(Color.black, 1);
    imgLabel.setBorder(blackline);
    
    JPanel imgWrapperPanel = new JPanel(new GridBagLayout());
    imgWrapperPanel.setBackground(Color.WHITE);
    imgWrapperPanel.add(imgLabel);
    
    
    imgLabel.addMouseListener(new MouseAdapter() {
        @Override
        public void mouseClicked(MouseEvent e) {
             new BookClick(book.id).setVisible(true); 
        }
    });
  
    // 커서를 이미지에 가져다 대면 손 모양 커서로 변경
    imgLabel.setCursor(new java.awt.Cursor(java.awt.Cursor.HAND_CURSOR));

    
    JPanel infoPanel = new JPanel();
    infoPanel.setLayout(new BorderLayout());
    infoPanel.setBackground(Color.WHITE);
    infoPanel.setBorder(new EmptyBorder(10, 5, 5, 5)); // 내부 여백

    // 제목과 저자 추가
    JPanel textPanel = new JPanel();
    textPanel.setLayout(new GridLayout(2, 1)); // 2줄 (제목, 저자)
    textPanel.setBackground(Color.WHITE);

    JLabel titleLabel = new JLabel(book.title);
    titleLabel.setFont(new Font("맑은 고딕", Font.BOLD, 14));
    titleLabel.setHorizontalAlignment(JLabel.CENTER);

    JLabel authorLabel = new JLabel(book.type + " | " + book.author);
    authorLabel.setFont(new Font("맑은 고딕", Font.PLAIN, 11));
    authorLabel.setForeground(Color.GRAY);
    authorLabel.setHorizontalAlignment(JLabel.CENTER);

    textPanel.add(titleLabel);
    textPanel.add(authorLabel);

    // 삭제 버튼
    JButton delBtn = new JButton("⌫");
    delBtn.setContentAreaFilled(false);
    delBtn.setCursor(new java.awt.Cursor(java.awt.Cursor.HAND_CURSOR));
    
    delBtn.addActionListener(e -> {
        
        int result = JOptionPane.showConfirmDialog(this, "정말 삭제하시겠습니까?", "삭제 확인", JOptionPane.YES_NO_OPTION);

        if (result == JOptionPane.YES_OPTION) {
            System.out.println("삭제 요청 book_id: " + book.id);

            try {
                dbConnect.DB db = new dbConnect.DB();
                db.dbOpen();

                String sql = "DELETE FROM book_memories " +
                             "WHERE book_id = " + book.id + " " +
                             "AND user_id = " + currentUserId;

                int count = db.dbStmt.executeUpdate(sql);

                db.dbClose();

                if (count > 0) {
                    JOptionPane.showMessageDialog(this, "삭제되었습니다.");
                    loadBookList(currentUserId); 
                } else {
                    JOptionPane.showMessageDialog(this, "삭제할 데이터를 찾지 못했습니다.");
                }

            } catch (Exception ex) {
                System.out.println("Delete Error: " + ex.getMessage());
                JOptionPane.showMessageDialog(this, "삭제 중 오류가 발생했습니다.");
            }
        }
    });
    
    // 하단 패널 조립
    infoPanel.add(textPanel, BorderLayout.CENTER);
    infoPanel.add(delBtn, BorderLayout.EAST); // 오른쪽에 삭제 버튼

    // 상단, 하단 패널 합치기
    cardPanel.add(imgWrapperPanel, BorderLayout.CENTER); 
    cardPanel.add(infoPanel, BorderLayout.SOUTH); 

    return cardPanel;
}
    
    
