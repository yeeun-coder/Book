    private void btnSignUpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSignUpActionPerformed
        String name;
        String nickname;
        String email;
        String pw;
        String pw_check;
        
        name =      txtName.getText().trim();
        nickname =  txtNickName.getText().trim();
        email =     txtEmail.getText().trim();
        pw =        String.valueOf(txtPw.getPassword());
        pw_check =  String.valueOf(txtPwCheck.getPassword());
        
        if (name.isBlank() || email.isBlank() || pw.isBlank() || pw_check.isBlank()) {
            
            javax.swing.JOptionPane.showMessageDialog(this, "모든 입력칸을 채워주세요.");
            return;
        }
        
        // 이메일 중복 체크
        try {
            String SQL = "select email from users where email = '" + email + "'";
            dbConnect.DB db = new dbConnect.DB();
            db.dbOpen();
            db.dbRs = db.dbStmt.executeQuery(SQL);
            if (db.dbRs.next()) {                           
                javax.swing.JOptionPane.showMessageDialog(this, "동일한 이메일이 존재합니다.");
                return;
            }
            
        } catch (Exception e) {
            System.out.println("SQL Exception : " + e.getMessage());
        }
        
        // 비밀번호 체크
        if (!pw.equals(pw_check)) {
            lblAlert.setText("비밀번호가 다릅니다.");
            jDialog1.setVisible(true);
            return;
        }
        
        // DB에 데이터 입력
        try {
            dbConnect.DB db = new dbConnect.DB();
            String SQL;
            SQL  = "insert into users values ( ";
            SQL += "NULL, ";
            SQL += "'" + email + "', ";
            SQL += "'" + pw + "', ";
            SQL += "'" + name + "', ";
            if (!nickname.isBlank()) SQL += "'" + nickname + "', ";
            else SQL += "NULL, ";
            SQL += "DEFAULT)";
            
            db.dbOpen();
            db.dbStmt.executeUpdate(SQL);
            db.dbClose();
            
            javax.swing.JOptionPane.showMessageDialog(this, "회원가입 되었습니다.");
            dispose();
        } catch (Exception e) {
            System.out.println("SQLException : " + e.getMessage());
        }
    }//GEN-LAST:event_btnSignUpActionPerformed

