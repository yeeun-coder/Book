    private void btnResetPWActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResetPWActionPerformed
        String email = txtEmail.getText().trim();
        String pw    = String.valueOf(txtPw.getPassword());
        String pwCheck = String.valueOf(txtPwCheck.getPassword());
        
        if (email.isBlank() || pw.isBlank() || pwCheck.isBlank()) {
            JOptionPane.showMessageDialog(this, "모든 필드를 입력해야 합니다.");
            return;
        }
        if (!pw.equals(pwCheck)) {
            JOptionPane.showMessageDialog(this, "새 비밀번호가 일치하지 않습니다.");
            return;
        }


        // DB 업데이트
        String sql = "UPDATE users SET password = '" + pw + "' WHERE email = '" + email + "'";
        
        try {
            DB db = new DB();
            db.dbOpen();

            System.out.println("실행할 쿼리: " + sql);
            int count = db.dbStmt.executeUpdate(sql);
            db.dbClose();

            if (count > 0) {
                JOptionPane.showMessageDialog(this, "비밀번호가 성공적으로 재설정되었습니다.");
                dispose();
            } else {
                JOptionPane.showMessageDialog(this, "해당 이메일 주소를 가진 사용자를 찾을 수 없습니다.");
            }
        } catch (Exception e) {
            System.out.println("Password Reset Error: " + e.getMessage());
            JOptionPane.showMessageDialog(this, "비밀번호 재설정 중 오류가 발생했습니다.");
        }
    }//GEN-LAST:event_btnResetPWActionPerformed

